enum class Category(val label: String) { BOARD("ボードゲーム"), CARD("カードゲーム") }

/** 設定の選択肢(盤の大きさなど)。values は (保存する値, 表示名) */
/**
 * 設定の1項目。group は設定の画面でまとめる板("rule" = ルール、"local" = ローカルルール)、hint は項目の下の1行の説明。
 */
class OptionSpec(val key: String, val label: String, val values: List<Pair<String, String>>, val default: String, val group: String = "rule", val hint: String? = null)

/** 説明画面の1項目 */
class Section(val title: String, val body: String, val demos: List<String> = emptyList())

/**
 * 収録ゲーム1つ分の情報。def が null のゲームは、まだ遊べない(次の段階で実装する)。
 * 説明文は実装している規則と一致させること。
 */
class GameInfo(
    val id: String,
    val no: Int,
    val name: String,
    val category: Category,
    val players: String,
    val intro: String,
    val def: GameDef<*>? = null,
    val sections: List<Section> = emptyList(),
    options: List<OptionSpec> = emptyList(),
    /** 席ごとの呼び名(先手・後手など) */
    val seatNames: List<String> = listOf("先手", "後手"),
) {
    val options: List<OptionSpec> = options + if (def != null) listOfNotNull(
        OptionSpec("moveSeconds", "1手の制限時間", listOf("0" to "なし", "15" to "15秒", "30" to "30秒", "60" to "60秒", "120" to "120秒"), "0", group = "time"),
        OptionSpec("timeoutRule", "時間が切れたら", listOf("move" to "ランダムな一手", "lose" to "負け"), "move", group = "time", hint = "「負け」は2人で遊ぶ時だけ。3人以上はランダムな一手"),
        // 通信対戦の「待った」(全員の了承が要る)。待ったのないゲーム(札を引く・サイコロを振るなど)には出さない
        if (def.undoAllowed) OptionSpec("onlineUndo", "「待った」の回数(1人あたり)", listOf("0" to "0回", "1" to "1回", "3" to "3回", "-1" to "制限なし"), "0", group = "online") else null,
    ) else emptyList()
    val playable: Boolean get() = def != null
}

